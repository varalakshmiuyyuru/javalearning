package com.corejava.controlflow.whiledemos;



// Print the numbers from 1 to 5
public class WhileDemo {
	
	public static void main(String[] args) {
		
		//Using while loop
		int i =1;
		
		while(i<=10) {
			System.out.println(i);
			
			// to print consecurtie numbers
			i++;   //i=i+1;
			
			//to print even numnbers
			//i+=2;  //i=i+2
			
		}
		
		
	}

}
